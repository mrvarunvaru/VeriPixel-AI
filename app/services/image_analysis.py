import base64
from concurrent.futures import ThreadPoolExecutor, as_completed
import io
import json
import os
from typing import Any

from PIL import Image, UnidentifiedImageError

MAX_UPLOAD_BYTES = 12 * 1024 * 1024
SUPPORTED_FORMATS = {"JPEG", "PNG", "WEBP", "GIF", "BMP", "TIFF"}


def inspect_image(content: bytes) -> tuple[Image.Image, dict[str, Any]]:
    try:
        image = Image.open(io.BytesIO(content))
        image.verify()
        image = Image.open(io.BytesIO(content))
    except (UnidentifiedImageError, OSError, Image.DecompressionBombError) as exc:
        raise ValueError("The upload is not a readable image file.") from exc

    if image.format not in SUPPORTED_FORMATS:
        raise ValueError("Use a JPEG, PNG, WebP, GIF, BMP, or TIFF image.")

    width, height = image.size
    if width * height > 40_000_000:
        raise ValueError("Image dimensions exceed the 40-megapixel safety limit.")

    exif_data = image.getexif()
    exif_names = {256: "width", 257: "height", 271: "camera_make", 272: "camera_model", 305: "software", 306: "date_time", 274: "orientation"}
    metadata: dict[str, Any] = {
        "format": image.format,
        "width": width,
        "height": height,
        "mode": image.mode,
        "file_size_bytes": len(content),
        "exif": {},
    }
    for key, value in exif_data.items():
        name = exif_names.get(key)
        if name and value is not None:
            metadata["exif"][name] = str(value)[:160]

    return image.copy(), metadata


def analyze_image(image: Image.Image, metadata: dict[str, Any]) -> dict[str, Any]:
    providers = _configured_providers()
    if not providers:
        return {
            "assessment": "inconclusive",
            "confidence": 0,
            "summary": "Visual AI analysis is not configured. Available file metadata cannot determine whether an image was generated by AI.",
            "details": {"subjects": [], "scene": "Not analyzed", "visible_text": [], "visual_style": "Not analyzed"},
            "signals": [],
            "caveats": ["Metadata is descriptive, not proof of image origin.", "Configure an OpenAI API key for a tentative origin assessment and/or an Anthropic API key for a second visual description."],
            "metadata": metadata,
            "analysis_mode": "metadata-only",
            "providers": [],
            "workflow": ["Image validated", "Dimensions and embedded metadata inspected", "Vision stage skipped: no API key"],
        }

    provider_results, provider_errors = _run_providers(image, metadata, providers)
    if not provider_results:
        failures = "; ".join(f"{name}: {message}" for name, message in provider_errors.items())
        raise RuntimeError(f"All configured vision providers failed. {failures}")

    vision = provider_results.get("openai", {})
    assessment = vision.get("assessment", "inconclusive")
    if assessment not in {"likely_ai_generated", "likely_camera_captured", "inconclusive"}:
        assessment = "inconclusive"
    try:
        confidence = max(0, min(100, int(vision.get("confidence", 0))))
    except (TypeError, ValueError):
        confidence = 0

    successful_providers = list(provider_results)
    combined = _combine_descriptions(provider_results)
    assessment_results = [
        result["assessment"]
        for result in provider_results.values()
        if result.get("assessment") in {"likely_ai_generated", "likely_camera_captured", "inconclusive"}
    ]
    if len(set(assessment_results)) > 1:
        assessment = "inconclusive"
        confidence = min(confidence, 50)
    caveats = _merge_lists(provider_results, "caveats")
    if "openai" not in provider_results:
        caveats.append("No configured origin-assessment provider completed an analysis; visual descriptions alone cannot determine image origin.")
    if provider_errors:
        caveats.append("Some configured providers failed: " + "; ".join(f"{name}: {message}" for name, message in provider_errors.items()))
    return {
        "assessment": assessment,
        "confidence": confidence,
        "summary": str(combined.get("summary") or vision.get("summary", "No summary was returned."))[:1200],
        "details": {
            "subjects": _merge_lists(provider_results, "subjects"),
            "scene": str(combined.get("scene", "Not described."))[:500],
            "visible_text": _merge_lists(provider_results, "visible_text"),
            "visual_style": str(combined.get("visual_style", "Not described."))[:500],
        },
        "signals": _merge_lists(provider_results, "signals"),
        "caveats": caveats or ["Visual clues are probabilistic and are not forensic proof of origin."],
        "metadata": metadata,
        "analysis_mode": "multi-provider" if len(successful_providers) > 1 else "vision-assisted",
        "providers": successful_providers,
        "provider_status": {name: "complete" if name in provider_results else "failed" for name in providers},
        "provider_assessments": {
            name: {"assessment": result.get("assessment", "not_provided"), "confidence": result.get("confidence")}
            for name, result in provider_results.items()
        },
        "workflow": ["Image validated", "Dimensions and embedded metadata inspected", "Configured vision providers reviewed image", "Evidence and uncertainty summarized"],
    }


def _prepare_image(image: Image.Image) -> str:
    buffer = io.BytesIO()
    safe_image = image.convert("RGB")
    safe_image.thumbnail((1280, 1280))
    safe_image.save(buffer, format="JPEG", quality=82, optimize=True)
    return base64.b64encode(buffer.getvalue()).decode("ascii")


def _configured_providers() -> dict[str, tuple[str, str]]:
    providers: dict[str, tuple[str, str]] = {}
    openai_key = os.getenv("OPENAI_API_KEY")
    anthropic_key = os.getenv("ANTHROPIC_API_KEY")
    if openai_key:
        providers["openai"] = (openai_key, os.getenv("OPENAI_VISION_MODEL", "gpt-4o-mini"))
    if anthropic_key:
        providers["anthropic"] = (anthropic_key, os.getenv("ANTHROPIC_VISION_MODEL", "claude-haiku-4-5"))
    return providers


def _run_providers(
    image: Image.Image,
    metadata: dict[str, Any],
    providers: dict[str, tuple[str, str]],
) -> tuple[dict[str, dict[str, Any]], dict[str, str]]:
    image_base64 = _prepare_image(image)
    results: dict[str, dict[str, Any]] = {}
    errors: dict[str, str] = {}
    with ThreadPoolExecutor(max_workers=len(providers)) as executor:
        futures = {
            executor.submit(_ask_provider, name, credentials, image_base64, metadata): name
            for name, credentials in providers.items()
        }
        for future in as_completed(futures):
            name = futures[future]
            try:
                results[name] = future.result()
            except Exception as exc:
                errors[name] = str(exc)[:250]
    return {name: results[name] for name in providers if name in results}, errors


def _ask_provider(name: str, credentials: tuple[str, str], image_base64: str, metadata: dict[str, Any]) -> dict[str, Any]:
    api_key, model = credentials
    if name == "openai":
        prompt = _analysis_prompt(metadata, assess_origin=True)
        return _ask_openai(api_key, model, prompt, image_base64)
    prompt = _analysis_prompt(metadata, assess_origin=False)
    return _ask_anthropic(api_key, model, prompt, image_base64)


def _analysis_prompt(metadata: dict[str, Any], assess_origin: bool) -> str:
    output_fields = (
        "assessment (likely_ai_generated|likely_camera_captured|inconclusive), confidence (0-100, tentative), "
        if assess_origin else ""
    )
    origin_instruction = (
        "Give only a tentative visual origin assessment, never forensic certainty; use inconclusive when evidence is weak. "
        if assess_origin else
        "Do not assess whether this image is AI-generated or authentic; report visual description only. "
    )
    return (
        "Analyze this image carefully and concisely. Describe only observable content. "
        f"{origin_instruction}Do not infer identity or sensitive traits. Treat metadata as context, not proof. "
        f"Return a JSON object with: {output_fields}summary, subjects (short-string array), scene, visible_text (array), "
        "visual_style, signals (observable clues array), caveats (array). "
        f"File metadata: {json.dumps(metadata, ensure_ascii=True)}"
    )


def _ask_openai(api_key: str, model: str, prompt: str, image_base64: str) -> dict[str, Any]:
    from openai import OpenAI

    client = OpenAI(api_key=api_key, timeout=45.0, max_retries=1)
    response = client.chat.completions.create(
        model=model,
        temperature=0.1,
        response_format={"type": "json_object"},
        messages=[{"role": "user", "content": [
            {"type": "text", "text": prompt},
            {"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{image_base64}", "detail": "auto"}},
        ]}],
    )
    content = response.choices[0].message.content or "{}"
    result = json.loads(content)
    return result if isinstance(result, dict) else {}


def _ask_anthropic(api_key: str, model: str, prompt: str, image_base64: str) -> dict[str, Any]:
    from anthropic import Anthropic

    client = Anthropic(api_key=api_key, timeout=45.0, max_retries=1)
    response = client.messages.create(
        model=model,
        max_tokens=700,
        temperature=0.1,
        messages=[{"role": "user", "content": [
            {"type": "image", "source": {"type": "base64", "media_type": "image/jpeg", "data": image_base64}},
            {"type": "text", "text": prompt},
        ]}],
    )
    content = "\n".join(block.text for block in response.content if getattr(block, "type", None) == "text")
    start, end = content.find("{"), content.rfind("}")
    if start < 0 or end < start:
        raise ValueError("Provider response did not contain a JSON report.")
    result = json.loads(content[start:end + 1])
    if not isinstance(result, dict):
        raise ValueError("Provider response was not a JSON object.")
    return result


def _combine_descriptions(results: dict[str, dict[str, Any]]) -> dict[str, str]:
    values: dict[str, str] = {}
    for field in ("summary", "scene", "visual_style"):
        descriptions = [str(result[field]).strip() for result in results.values() if result.get(field)]
        if descriptions:
            values[field] = " / ".join(dict.fromkeys(descriptions))[:1200]
    return values


def _merge_lists(results: dict[str, dict[str, Any]], field: str) -> list[str]:
    merged: list[str] = []
    for result in results.values():
        merged.extend(_string_list(result.get(field)))
    return list(dict.fromkeys(merged))[:12]


def _string_list(value: Any) -> list[str]:
    if not isinstance(value, list):
        return []
    return [str(item)[:300] for item in value[:12] if item is not None]
